import { build } from 'vite';
import { readFile, readdir, rm, mkdir, writeFile } from 'node:fs/promises';
import { resolve, relative } from 'node:path';

const root = process.cwd();
const appConfigPath = resolve(root, 'src/core/app-config.ts');
const packagePath = resolve(root, 'package.json');
const entryPath = resolve(root, 'src/standalone/standalone-entry.ts');
const generatedPath = resolve(root, 'src/standalone/generated-runtime.ts');
const temporaryDirectory = resolve(root, 'qa-dist/standalone-runtime-build');

const appConfig = await readFile(appConfigPath, 'utf8');
const versionMatch = appConfig.match(/APP_VERSION\s*=\s*'([^']+)'/);
if (!versionMatch) throw new Error('APP_VERSION could not be read from src/core/app-config.ts.');
const version = versionMatch[1];
const packageJson = JSON.parse(await readFile(packagePath, 'utf8'));
if (packageJson.version !== version) {
  throw new Error(`Package version ${packageJson.version} does not match application version ${version}.`);
}

await rm(temporaryDirectory, { recursive: true, force: true });
await mkdir(temporaryDirectory, { recursive: true });

await build({
  root,
  configFile: false,
  publicDir: false,
  base: './',
  logLevel: 'warn',
  worker: { format: 'iife' },
  build: {
    outDir: temporaryDirectory,
    emptyOutDir: true,
    target: 'es2022',
    minify: 'esbuild',
    sourcemap: false,
    cssCodeSplit: false,
    assetsInlineLimit: Number.MAX_SAFE_INTEGER,
    lib: {
      entry: entryPath,
      name: 'ScientificAnimationStandalone',
      formats: ['iife'],
      fileName: () => 'standalone-runtime.js',
    },
    rollupOptions: {
      output: {
        inlineDynamicImports: true,
      },
    },
  },
});

const entries = await readdir(temporaryDirectory, { recursive: true, withFileTypes: true });
const outputFiles = entries
  .filter((entry) => entry.isFile())
  .map((entry) => resolve(entry.parentPath, entry.name));
const javascriptFiles = outputFiles.filter((path) => path.endsWith('.js'));
if (javascriptFiles.length !== 1 || outputFiles.length !== 1) {
  throw new Error(
    `Standalone runtime must produce exactly one JavaScript file. Produced: ${outputFiles
      .map((path) => relative(root, path))
      .join(', ')}`,
  );
}

const source = await readFile(javascriptFiles[0], 'utf8');
const requiredMarkers = [
  '__SCIENCE_STANDALONE_RUNTIME_VERSION__',
  '__SCIENCE_STANDALONE_RUNTIME__',
  version,
  'moon-orbit-plane',
  'MOON_HIERARCHY_INVALID',
  'mercury',
  'venus',
  'earth',
  'mars',
  'jupiter',
  'saturn',
  'uranus',
  'neptune',
  'moon',
];
const missingMarkers = requiredMarkers.filter((marker) => !source.includes(marker));
if (missingMarkers.length) {
  throw new Error(`Generated standalone runtime is missing markers: ${missingMarkers.join(', ')}`);
}
if (/\bimport\s*\(/.test(source)) {
  throw new Error('Generated standalone runtime contains a dynamic import.');
}

const generated = `// AUTO-GENERATED by scripts/build-standalone-runtime.js. Do not edit manually.\n` +
  `export const GENERATED_STANDALONE_RUNTIME_VERSION = ${JSON.stringify(version)} as const;\n` +
  `export const GENERATED_STANDALONE_RUNTIME_BYTES = ${Buffer.byteLength(source, 'utf8')} as const;\n` +
  `export const GENERATED_STANDALONE_RUNTIME_SOURCE = ${JSON.stringify(source)};\n`;
await writeFile(generatedPath, generated, 'utf8');
await rm(temporaryDirectory, { recursive: true, force: true });
console.log(`Generated standalone runtime v${version} (${Buffer.byteLength(source, 'utf8')} bytes).`);
